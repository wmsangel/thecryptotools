const bySlug = new Map(coins.map((c) => [c.slug, c]));

export function getCoin(slug: string): Coin | undefined {
  return bySlug.get(slug);
}

export function getAllCoinSlugs(): string[] {
  return coins.map((c) => c.slug);
}

/** Coins sorted the way we always want to show them (rough market-cap order). */
export function sortedCoins(): Coin[] {
  return [...coins].sort((a, b) => a.order - b.order);
}

/** Coins that can be staked — used by the staking pairing spec. */
export function stakingCoins(): Coin[] {
  return sortedCoins().filter((c) => c.staking);
}
