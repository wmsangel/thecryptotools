/**
 * Пишет карту назначений для /go: src/lib/go-map.generated.json, из которой
 * читает Pages Function functions/go/[[path]].js (гейт жеста + подписанный токен).
 *
 * Раньше здесь генерировались статические `/go/<slug>  <url>  302` в
 * out/_redirects — их брали боты и префетч (0 конверсий при тысячах «кликов»,
 * аудит 27.11.2026). Статические правила _redirects срабатывают раньше Function и
 * перекрыли бы гейт, поэтому теперь скрипт их НЕ пишет, а старый сгенерированный
 * блок (если он остался в out/_redirects) вычищает.
 *
 * Правда о реф-ссылках по-прежнему живёт в одном месте — platforms.ts; сети без
 * записи в platforms.ts (ручные офферы) перечислены в EXTRA ниже.
 *
 * Запускается в конце `npm run build`. Идемпотентно. Файл карты коммитится
 * (детерминированный, сортированный): правка ссылки видна в git diff.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { platforms as PLATFORMS } from "../src/lib/platforms";
import { isReferralLink } from "../src/lib/affiliate";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_REDIRECTS = join(ROOT, "out", "_redirects");
const MAP_FILE = join(ROOT, "src", "lib", "go-map.generated.json");
const START = "# --- /go/* affiliate redirects (generated by scripts/build-go-redirects.ts) ---";
const END = "# --- end /go/* ---";

/** Network by tracker host — decides which sub-id parameter the function adds. */
function netOf(url: string): "indoleads" | "admitad" | "direct" {
  let host = "";
  try {
    host = new URL(url).hostname.replace(/^www\./, "");
  } catch {
    return "direct";
  }
  // The owner's own Indoleads click-tracker domains (sub-id parameter: p1).
  if (["o10o.xyz", "i05o.xyz", "gettracker.net"].includes(host)) return "indoleads";
  // Admitad tracking domains (sub-id parameter: subid).
  if (["ntzgd.com", "xcdus.com", "qbzdl.com"].includes(host)) return "admitad";
  return "direct"; // exchange / brand programs with a fixed referral code, no sub-id
}

/** Offers that have a /go slug but no platforms.ts entry (moved here from public/_redirects). */
const EXTRA: Record<string, string> = {
  "2ndnumber": "https://qbzdl.com/g/q9khw5u698ff871df07d7c1db20106/",
  ishosting: "https://xcdus.com/g/t7pdcms1vhff871df07df6378a678b/",
  protonvpn: "https://ntzgd.com/g/px9exodsjkff871df07d08612d8f27/",
  expressvpn: "https://gettracker.net/6ac88e36883aa",
};

type Entry = { u?: string; n: string };
const map: Record<string, Entry> = {};

// Only platforms with a REAL referral link get a /go entry; a plain homepage
// earns nothing and is linked directly (platformLink in affiliate.ts).
for (const p of PLATFORMS) {
  if (p.slug && p.url && isReferralLink(p.url)) map[p.slug] = { u: p.url, n: netOf(p.url) };
}
for (const [slug, url] of Object.entries(EXTRA)) map[slug] = { u: url, n: netOf(url) };
// Amazon: the destination is built per click from the signed query (see the function).
map["amazon"] = { n: "amazon" };

const sorted = Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(MAP_FILE, JSON.stringify(sorted, null, 2) + "\n");

// Purge a stale generated block from out/_redirects so it cannot shadow the function.
if (existsSync(OUT_REDIRECTS)) {
  const t = readFileSync(OUT_REDIRECTS, "utf8");
  const s = t.indexOf(START);
  if (s !== -1) {
    const e = t.indexOf(END);
    const before = t.slice(0, s).replace(/\s+$/, "");
    const after = e === -1 ? "" : t.slice(e + END.length).replace(/^\s+/, "").replace(/\s+$/, "");
    writeFileSync(OUT_REDIRECTS, (after ? `${before}\n\n${after}` : before) + "\n");
  }
}

const left = existsSync(OUT_REDIRECTS) ? (readFileSync(OUT_REDIRECTS, "utf8").match(/^\/go\//gm) ?? []).length : 0;
console.log(`/go map: ${Object.keys(sorted).length} назначений → ${MAP_FILE}; статических /go в out/_redirects: ${left}`);
if (left > 0) {
  console.error("ОШИБКА: в out/_redirects остались статические /go/* — они перекроют Function");
  process.exit(1);
}
